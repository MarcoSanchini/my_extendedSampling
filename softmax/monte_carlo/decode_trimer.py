"""
zero_polymer as a trimer: decode three copies of the HA ectodomain joined by
poly-glycine linkers, and compare the result with the experimental radius of
gyration of a real HA structure.

Why: HA is a homotrimer. The HA2 helices of each protomer pack against the
other two, so a sequence-only, single-copy decode has nothing holding them in
place -- which is the standing explanation for why the zero_polymer reference
itself decodes to pLDDT 0.51-0.63 and Rg 45-70 A (DEVLOG, 2026-11-02). ESM3 is
not a multimer predictor, but the usual trick is to give it the chains as one
sequence separated by a long glycine linker. If that raises pLDDT and brings Rg
near the experimental value, the monomer framing was the problem; if it does
not, this decoder cannot describe HA at all and we need a real multimer
predictor.

What it decodes (all with the same model, generate() path and metrics as
decode-ref / decode_controls.py):

  monomer       the ectodomain alone, as the baseline already measured
  trimer        --n-chains copies of it joined by --linker G residues

and reports, with the linker residues excluded everywhere:

  Rg_ca         over all protomer CA atoms (the assembly's Rg)
  Rg_protomer   per copy, mean and spread (each copy's own compactness)
  mean_plddt    over protomer residues; the linkers are reported separately,
                since a disordered linker would otherwise drag the mean down

Experimental reference (--pdb): the CA radius of gyration of a deposited HA
structure, computed from its biological assembly, overall and per chain. The
default 2HMG is an H3 (X-31) hemagglutinin; the script prints the chains and
residue counts it found, so check they look like an HA trimer before trusting
the number. Use --pdb '' to skip.

Note on what Rg can and cannot say here: HA's ectodomain is a ~135 A rod, and a
uniform rod of length l has Rg = l/sqrt(12) ~ 39 A, so a "compact globule"
estimate is the wrong yardstick. The experimental number from --pdb is the
yardstick.

Usage (on the GPU machine; needs network for --pdb):
    python decode_trimer.py --num-steps 8 32 --out nsites_study/structure/trimer.csv
    python decode_trimer.py --residues 16:529 --n-chains 3 --linker 25 --num-steps 32
    python decode_trimer.py --pdb 4HMG --num-steps 8

~1600 residues is far longer than anything decoded here so far, so start with
one step count; if it runs out of memory, try --n-chains 2 first.
"""
import argparse
import gzip
import io
import os
import sys
import urllib.request

MONTE_CARLO_DIR = os.path.dirname(os.path.abspath(__file__))
CODE_DIR = os.path.abspath(os.path.join(MONTE_CARLO_DIR, "../code"))
CUSTOMS_DIR = os.path.abspath(os.path.join(MONTE_CARLO_DIR, "../../customs"))
for p in (MONTE_CARLO_DIR, CODE_DIR, CUSTOMS_DIR, os.path.join(CODE_DIR, "tests")):
	if p not in sys.path:
		sys.path.insert(0, p)

import numpy as np
import pandas as pd

RCSB_ASSEMBLY = "https://files.rcsb.org/download/{}.pdb1.gz"


def experimental_rg(pdb_id):
	"""CA radius of gyration of a deposited structure's first biological
	assembly: (overall Rg, [(chain label, n residues, Rg), ...]).

	The assembly file repeats the asymmetric unit as several MODELs when the
	trimer is generated by symmetry, so a chain is keyed by (model, chain id).
	Plain PDB parsing, no new dependency: ATOM records, CA only, first altloc.
	"""
	with urllib.request.urlopen(RCSB_ASSEMBLY.format(pdb_id), timeout=120) as r:
		raw = gzip.decompress(r.read()).decode("latin-1")
	chains, model = {}, 1
	for line in io.StringIO(raw):
		if line.startswith("MODEL"):
			model = int(line[10:14])
		elif line.startswith("ATOM") and line[12:16].strip() == "CA" and line[16] in " A":
			key = f"{model}{line[21]}"
			xyz = (float(line[30:38]), float(line[38:46]), float(line[46:54]))
			chains.setdefault(key, []).append(xyz)
	if not chains:
		raise SystemExit(f"{pdb_id}: no CA atoms found in the assembly file")

	def rg(points):
		a = np.asarray(points)
		return float(np.sqrt(((a - a.mean(0)) ** 2).sum(1).mean()))

	per_chain = [(k, len(v), rg(v)) for k, v in sorted(chains.items())]
	return rg([xyz for v in chains.values() for xyz in v]), per_chain


def main():
	ap = argparse.ArgumentParser()
	ap.add_argument("--ref", default="zero_polymer")
	ap.add_argument("--residues", default="16:529",
		help="the part of the reference to repeat, START:END as a python slice "
			 "(default 16:529, the ectodomain: no signal peptide, no TM/tail)")
	ap.add_argument("--n-chains", type=int, default=3)
	ap.add_argument("--linker", type=int, default=25, help="glycines between copies")
	ap.add_argument("--num-steps", type=int, nargs="+", default=[8, 32])
	ap.add_argument("--pdb", default="2HMG", help="experimental structure for Rg; '' to skip")
	ap.add_argument("--seed", type=int, default=0)
	ap.add_argument("--out", default="nsites_study/structure/trimer.csv")
	args = ap.parse_args()

	import torch
	from compute_structural_metrics import decode_structure_with_mask, radius_of_gyration, CA_IDX
	from classes.rate_sampler import ExtendedProteinRateSampler
	from classes.ExtendedProtein import ExtendedProtein
	from utils.predictions import init_structure_config
	from references import get_reference

	_, ref_seq = get_reference(args.ref)
	unit = ref_seq[slice(*map(int, args.residues.split(":")))] if args.residues else ref_seq
	linker = "G" * args.linker
	n_unit = len(unit)

	def spans(n_chains):
		"""(protomer index ranges, linker index range) in the built sequence."""
		prot, link, pos = [], [], 0
		for c in range(n_chains):
			prot.append((pos, pos + n_unit))
			pos += n_unit
			if c < n_chains - 1:
				link.append((pos, pos + args.linker))
				pos += args.linker
		return prot, link

	builds = [("monomer", unit, 1)]
	if args.n_chains > 1:
		builds.append((f"{args.n_chains}-mer_G{args.linker}", linker.join([unit] * args.n_chains), args.n_chains))
	print(f"Unit: residues {args.residues} of {args.ref}, {n_unit} aa")
	for label, seq, _ in builds:
		print(f"  {label}: {len(seq)} residues")

	device = torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
	sampler = ExtendedProteinRateSampler(config_settings={})
	sampler.model.to(device)

	rows = []
	for num_steps in args.num_steps:
		config = init_structure_config(num_steps=num_steps)
		for label, seq, n_chains in builds:
			torch.manual_seed(args.seed)
			eprot = ExtendedProtein(sequence=seq, requires_grad=False, device=device)
			eprot.expand()
			try:
				positions, mask, plddt = decode_structure_with_mask(sampler.model, eprot, config)
			except (AttributeError, RuntimeError) as exc:
				print(f"  {label} steps={num_steps}: decode failed ({type(exc).__name__}: {exc}); skipped", flush=True)
				continue
			prot, link = spans(n_chains)
			ca = positions[:, CA_IDX, :]
			keep = np.concatenate([np.arange(a, b) for a, b in prot])
			rg_all = radius_of_gyration(ca[torch.as_tensor(keep)])
			rg_each = [radius_of_gyration(ca[a:b]) for a, b in prot]
			pl = plddt.float().numpy() if plddt is not None else None
			row = {"label": label, "num_steps": num_steps, "n_chains": n_chains, "length": len(seq),
				"Rg_ca": rg_all, "Rg_protomer_mean": float(np.mean(rg_each)),
				"Rg_protomer_min": float(np.min(rg_each)), "Rg_protomer_max": float(np.max(rg_each)),
				"mean_plddt": float(pl[keep].mean()) if pl is not None else float("nan"),
				"mean_plddt_linker": float(np.mean([pl[a:b].mean() for a, b in link])) if pl is not None and link
					else float("nan")}
			rows.append(row)
			print(f"  {label} steps={num_steps}: Rg_ca={row['Rg_ca']:.2f}  "
				f"Rg_protomer={row['Rg_protomer_mean']:.2f} ({row['Rg_protomer_min']:.2f}-{row['Rg_protomer_max']:.2f})  "
				f"pLDDT={row['mean_plddt']:.3f}  pLDDT_linker={row['mean_plddt_linker']:.3f}", flush=True)

	df = pd.DataFrame(rows)
	os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
	df.to_csv(args.out, index=False)
	print()
	print(df.round(3).to_string(index=False))
	print(f"\nSaved -> {args.out}")

	if args.pdb:
		rg_exp, per_chain = experimental_rg(args.pdb)
		print(f"\nExperimental {args.pdb} (first biological assembly):")
		for key, n, rg in per_chain:
			print(f"  chain {key}: {n} residues, Rg_ca {rg:.2f} A")
		print(f"  all chains: {sum(n for _, n, _ in per_chain)} residues, Rg_ca {rg_exp:.2f} A")
		print("  (check the chains above look like an HA trimer: HA1 ~320 and HA2 ~175 residues per protomer)")


if __name__ == "__main__":
	main()
